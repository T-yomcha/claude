; =====================================================================
;  Задача 1. Поиск максимума в массиве (целые числа без знака, 16 бит)
;  Вариант 12: безадресная (стековая) система команд,
;              гарвардская архитектура (раздельные ОЗУ команд и данных)
;
;  ARR[0] — количество элементов N, далее N элементов массива.
;  Результат записывается в ячейку MAX.
;  В комментариях «стек:» показано содержимое стека, вершина — справа.
; =====================================================================

.data
ARR:    .word 10, 1200, 35, 40000, 7, 512, 65000, 999, 18, 27000, 64999
MAX:    .word 0         ; результат
PTR:    .word 0         ; указатель (адрес) текущего элемента
CNT:    .word 0         ; сколько элементов осталось просмотреть

.code
START:  PUSH 0
        MAX.            ; MAX := 0 (наименьшее беззнаковое число)
        ARR@            ; стек: N
        CNT.            ; CNT := N
        PUSH ARR+1
        PTR.            ; PTR := адрес первого элемента
        CNT@ PUSH 0 CMP ; N - 0: Z = 1, если массив пуст
        JZ DONE

LOOP:   PTR@ READ       ; стек: a          (a = ARR[i], косвенная адресация)
        DUP             ; стек: a a
        MAX@            ; стек: a a max
        SWAP            ; стек: a max a
        CMP             ; max - a: C = 1 (заём), если a > max;  стек: a
        JNC SKIP        ; a <= max — максимум не меняется
        DUP MAX.        ; MAX := a;  стек: a
SKIP:   DROP            ; стек пуст
        PTR@ INC PTR.   ; PTR := PTR + 1
        CNT@ DEC CNT.   ; CNT := CNT - 1  (Z = 1, когда CNT = 0)
        JNZ LOOP        ; повторять, пока остались элементы
DONE:   HALT
