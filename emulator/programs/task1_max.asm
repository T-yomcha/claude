; =====================================================================
;  Задача 1. Поиск максимума в массиве (целые числа без знака, 16 бит)
;  Вариант 12: безадресная (стековая) система команд,
;              гарвардская архитектура (раздельные ОЗУ команд и данных)
;
;  ARR[0] — количество элементов N, далее N элементов массива.
;  Массив ARR лежит с адреса 0 ОЗУ данных, поэтому адрес элемента ARR[i]
;  равен i: счётчик цикла i (от N до 1) хранится в стеке и одновременно
;  служит адресом элемента. Результат записывается в ячейку MAX.
;  В комментариях «стек:» показано содержимое стека, вершина — справа.
; =====================================================================

.data
ARR:    .word 10, 1200, 35, 40000, 7, 512, 65000, 999, 18, 27000, 64999   ; с адреса 0
MAX:    .word 0         ; результат

.code
START:  PUSH 0 MAX.     ; MAX := 0 (наименьшее беззнаковое число)
        ARR@            ; стек: i            (i := N)
        DUP PUSH 0 CMP  ; i - 0: Z = 1, если массив пуст
        JZ DONE

LOOP:   DUP READ        ; стек: i a          (a = ARR[i], адрес = i)
        DUP MAX@        ; стек: i a a max
        CMP             ; a - max: C = 1 (заём), если a < max;  стек: i a
        JC SKIP         ; a < max — максимум не меняется
        DUP MAX.        ; MAX := a;  стек: i a
SKIP:   DROP            ; стек: i
        DEC             ; i := i - 1  (Z = 1, когда i = 0)
        JNZ LOOP        ; повторять, пока остались элементы
DONE:   DROP            ; убрать счётчик — стек пуст
        HALT
