; =====================================================================
;  Задача 2. Свёртка двух массивов:  S = A[1]·B[1] + … + A[N]·B[N]
;  N = 6, целые числа без знака (16 бит).
;  Вариант 12: безадресная (стековая) система команд, гарвардская архитектура.
;
;  Длинная арифметика:
;    UMUL     — произведение 16 × 16 = 32 бита (два слова: старшее и младшее);
;    ADD/ADC  — сложение многословных чисел, перенос передаётся через флаг C.
;  Сумма хранится в трёх словах (48 бит) S2:S1:S0, потому что сумма
;  шести 32-битных произведений может не поместиться в 32 бита.
;  Начальное значение S = 0 задаётся в секции .data при загрузке программы.
;
;  Массив A лежит с адреса 0 ОЗУ данных, поэтому адрес A[i] равен i,
;  а адрес B[i] равен B + i. Счётчик цикла i (от N до 1) хранится в стеке.
;  В комментариях «стек:» показано содержимое стека, вершина — справа.
; =====================================================================

.data
A:      .word 6, 1000, 2000, 300, 40000, 5, 65535    ; с адреса 0, A[0] = N = 6
B:      .word 6, 70, 3000, 400, 50000, 6, 65535      ; B[0] = N = 6
S0:     .word 0         ; результат: младшее слово (биты 15..0)
S1:     .word 0         ; результат: среднее слово (биты 31..16)
S2:     .word 0         ; результат: старшее слово (биты 47..32)

.code
START:  A@              ; стек: i               (i := N)
LOOP:   DUP READ        ; стек: i a             (a = A[i], адрес = i)
        OVER PUSH B ADD READ  ; стек: i a b     (b = B[i], адрес = B + i)
        UMUL            ; стек: i мл ст         (a·b = ст:мл, 32 бита)
        SWAP            ; стек: i ст мл
        S0@ ADD S0.     ; S0 := S0 + мл;      C = перенос;  стек: i ст
        S1@ ADC S1.     ; S1 := S1 + ст + C;  C = перенос;  стек: i
        S2@ PUSH 0 ADC S2.  ; S2 := S2 + C
        DEC             ; i := i - 1  (Z = 1, когда i = 0)
        JNZ LOOP        ; повторять, пока остались элементы
        DROP            ; убрать счётчик — стек пуст
        HALT
